// Generates src/game/assetManifest.ts: the exact list of files under assets/
// the game ships, keyed by their path under assets/.
//
//   npm run assets:manifest                         write the manifest
//   node scripts/gen-asset-manifest.mjs --check     exit 1 if it is stale
//
// Sources, so the list is exact and never a folder glob (unused files must not
// be bundled):
//   - every string literal passed to assetUrl('…') in src/ (the homepage is a
//     separate marketing page and keeps its own URLs)
//   - every "file" in assets/data/models/*.jsonc (models referenced by data)
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';

const OUT = 'src/game/assetManifest.ts';

function walk(dir) {
    return readdirSync(dir).flatMap((name) => {
        const p = join(dir, name);
        return statSync(p).isDirectory() ? walk(p) : [p];
    });
}

export function collectAssetPaths() {
    const paths = new Set();
    const problems = [];
    for (const file of walk('src')) {
        if (!/\.(ts|tsx|js|mjs)$/.test(file) || file.startsWith(join('src', 'homepage'))) continue;
        if (file === OUT) continue;
        const text = readFileSync(file, 'utf8');
        for (const m of text.matchAll(/assetUrl\(\s*(['"`])([^'"`$]+)\1\s*\)/g)) paths.add(m[2]);
        // a URL built by hand from assets/ is a file the resolver can't replace
        for (const m of text.matchAll(/new URL\(\s*['"`](?:\.\.\/)+assets\//g)) {
            const line = text.slice(0, m.index).split('\n').length;
            problems.push(`${file}:${line}: hard-coded asset URL — use assetUrl('…') instead`);
        }
    }
    for (const file of walk('assets/data/models')) {
        if (!file.endsWith('.jsonc')) continue;
        for (const m of readFileSync(file, 'utf8').matchAll(/"file"\s*:\s*"([^"]+)"/g)) paths.add(m[1]);
    }
    for (const p of paths) {
        if (!existsSync(join('assets', p))) problems.push(`assets/${p} does not exist`);
    }
    return { paths: [...paths].sort(), problems };
}

export function renderManifest(paths) {
    const lines = paths.map((p) => `        '../../assets/${p}',`).join('\n');
    return `// GENERATED by \`npm run assets:manifest\` (scripts/gen-asset-manifest.mjs) — do not edit.
//
// Exactly the files under assets/ that the game loads, keyed by their path under
// assets/. Read through assetUrl() in ./assets.ts, never directly.

const RAW = import.meta.glob(
    [
${lines}
    ],
    { query: '?url', import: 'default', eager: true },
) as Record<string, string>;

/** path under assets/ → built URL */
export const BASE_ASSET_URLS: ReadonlyMap<string, string> = new Map(
    Object.entries(RAW).map(([key, url]) => [key.slice('../../assets/'.length), url]),
);
`;
}

const isMain = process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop());
if (isMain) {
    const { paths, problems } = collectAssetPaths();
    for (const p of problems) console.error(`FAIL ${p}`);
    const text = renderManifest(paths);
    if (process.argv.includes('--check')) {
        const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
        if (current !== text) {
            console.error(`FAIL ${OUT} is stale — run: npm run assets:manifest`);
            process.exit(1);
        }
        console.log(`ok   asset manifest is current (${paths.length} files)`);
    } else {
        writeFileSync(OUT, text);
        console.log(`wrote ${relative('.', OUT)} (${paths.length} files)`);
    }
    process.exit(problems.length ? 1 : 0);
}
